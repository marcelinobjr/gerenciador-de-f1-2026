/**
 * Busca URL direta de CDN pública do Google Photos para o nome do arquivo ou piloto
 */
export function getDriveStoragePhotoUrl(filenameOrPilotKey: string): string | null {
  if (!filenameOrPilotKey) return null

  // 1. Busca exata por nome de arquivo
  if (DRIVE_STORAGE_PHOTOS[filenameOrPilotKey]) {
    return DRIVE_STORAGE_PHOTOS[filenameOrPilotKey]
  }

  // 2. Busca ignorando extensão
  const baseKey = filenameOrPilotKey.replace(/\.(jpg|png|webp|jpeg)$/i, '').toLowerCase()
  for (const [key, url] of Object.entries(DRIVE_STORAGE_PHOTOS)) {
    const itemBase = key.replace(/\.(jpg|png|webp|jpeg)$/i, '').toLowerCase()
    if (itemBase === baseKey) {
      return url
    }
  }

  // 3. Busca por sufixo de piloto (ex: "verstappen", "bortoleto")
  for (const [key, url] of Object.entries(DRIVE_STORAGE_PHOTOS)) {
    const itemBase = key.replace(/\.(jpg|png|webp|jpeg)$/i, '').toLowerCase()
    if (itemBase.endsWith(`_${baseKey}`) || itemBase.includes(baseKey)) {
      return url
    }
  }

  return null
}
